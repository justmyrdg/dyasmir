import { randomInt } from 'node:crypto';

/** Fisher-Yates shuffle using a CSPRNG. Returns a new array. */
export function shuffled<T>(items: readonly T[]): T[] {
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = randomInt(i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
